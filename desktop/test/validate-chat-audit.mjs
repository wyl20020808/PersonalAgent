import {createServer} from 'vite';
import {build} from 'esbuild';
import {spawnSync} from 'node:child_process';
import {mkdirSync,writeFileSync} from 'node:fs';
import {fileURLToPath,pathToFileURL} from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
const desktop=fileURLToPath(new URL('..',import.meta.url));
const output=path.join(desktop,'validation-chat-audit');mkdirSync(output,{recursive:true});
await build({entryPoints:[path.join(desktop,'test/chat-presentation.test.ts')],outfile:path.join(output,'presentation.test.mjs'),bundle:true,platform:'node',format:'esm'});
const tests=spawnSync(process.execPath,['--test',path.join(output,'presentation.test.mjs')],{encoding:'utf8'});
writeFileSync(path.join(output,'unit-tests.txt'),tests.stdout+tests.stderr);assert.equal(tests.status,0,tests.stdout+tests.stderr);
const {chromium}=await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE??'D:/PersonalAgent/snake-validation/node_modules/playwright-core/index.mjs').href);
const server=await createServer({root:desktop,server:{host:'127.0.0.1',port:0},logLevel:'error'});
await server.listen();
let browser;
const errors=[];
try{
 browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH??'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
 const page=await browser.newPage({viewport:{width:1280,height:1100},deviceScaleFactor:1});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(server.resolvedUrls.local[0]+'test/chat-audit.html');
 await page.locator('[data-message-id="check"]').waitFor();
 await page.evaluate(()=>document.fonts.ready);
 const box=id=>page.locator(`[data-message-id="${id}"]`).boundingBox();
 const user=await box('user'),decision=await box('codex-decision'),execution=await box('codex');
 assert.ok(decision.x<execution.x,'Decision and execution must occupy opposite sides');
 assert.ok(Math.abs(user.x+user.width/2-640)<2,'User must be centered');
 for(const id of ['claude','codex','opencode'])assert.ok(await page.locator(`[data-message-id="${id}"] .agent-logo img`).evaluate(img=>img.complete&&img.naturalWidth>0),id+' official logo');
 const controller=page.locator('[data-message-id="check"] .message-content');
 assert.ok(await controller.evaluate(el=>parseFloat(getComputedStyle(el).paddingLeft)>=12),'Controller padding');
 assert.equal(await page.locator('[data-message-id="failure"] .tool-output').getAttribute('open'),'');
 await page.locator('.group-toggle').click();assert.equal(await page.locator('.group-children .group-message').count(),2);
 await page.locator('.group-toggle').click();
 await page.screenshot({path:path.join(output,'desktop.png'),fullPage:true});
 await page.locator('[data-message-id="check"]').screenshot({path:path.join(output,'controller.png')});
 await page.setViewportSize({width:480,height:1000});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No narrow viewport horizontal overflow');
 await page.screenshot({path:path.join(output,'narrow.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 writeFileSync(path.join(output,'result.json'),JSON.stringify({passed:true,fixture:true,headless:true,base:'32ec301e59868db120904c873ca123f6fc9b7743',checks:['role placement','user centered','three official logos loaded','Controller padding','failure output visible','group expansion','480px overflow','no page errors'],errors},null,2));
 console.log('PASS: 5 unit tests; 8 headless UI checks. '+output);
}finally{await browser?.close();await server.close();}
